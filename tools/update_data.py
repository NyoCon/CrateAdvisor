#!/usr/bin/env python3
"""Regenerates Data/Crates.lua: every Waylaid Crate and the material packages that fill it.

Source: wago.tools DB2 exports of the newest `wowf` build, or the build given as first argument.
The client does not know the materials as item IDs: a crate's use spell only has dummy effects
whose base points are the amounts, and its description names the materials ("- $M3 Bolt of
Mageweave"). The English names are resolved to item IDs via ItemSparse.

    python3 tools/update_data.py [build]
"""

import collections
import csv
import io
import json
import re
import sys
import urllib.request
from pathlib import Path

WAGO = "https://wago.tools"
ROOT = Path(__file__).resolve().parent.parent

CRATE_DESC = "$@spelldesc1308117"   # shared "Fills the crate with any one package ..." text
OPTION = re.compile(r"^- \$M(\d+) (.+?)(?:\|r)?\s*$")

# Names that belong to more than one item: the one that is actually traded
AMBIGUOUS = {
    "Dark Iron Ore": 11370,   # 11099 is an unused duplicate
}


def fetch(url):
    request = urllib.request.Request(url, headers={"User-Agent": "CrateAdvisor data tool"})
    with urllib.request.urlopen(request, timeout=300) as response:
        return response.read().decode("utf-8")


def table(name, build, locale=None):
    url = f"{WAGO}/db2/{name}/csv?build={build}" + (f"&locale={locale}" if locale else "")
    return list(csv.DictReader(io.StringIO(fetch(url))))


def newest_build():
    return json.loads(fetch(f"{WAGO}/api/builds"))["wowf"][0]["version"]


def lua_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    build = sys.argv[1] if len(sys.argv) > 1 else newest_build()
    print(f"build {build}")

    descriptions = {r["ID"]: r["Description_lang"] for r in table("Spell", build)}
    crate_spells = {sid for sid, d in descriptions.items() if d.startswith(CRATE_DESC)}

    effects = collections.defaultdict(dict)
    for r in table("SpellEffect", build):
        if r["SpellID"] in crate_spells:
            effects[r["SpellID"]][int(r["EffectIndex"])] = r

    spell_of_effect = {r["ID"]: r["SpellID"] for r in table("ItemEffect", build)}
    crate_items = collections.defaultdict(list)   # spell -> items
    for r in table("ItemXItemEffect", build):
        spell = spell_of_effect.get(r["ItemEffectID"])
        if spell in crate_spells:
            crate_items[spell].append(int(r["ItemID"]))

    sparse = table("ItemSparse", build)
    names = {int(r["ID"]): r["Display_lang"] for r in sparse}
    by_name = collections.defaultdict(list)
    for item_id, name in names.items():
        by_name[name].append(item_id)

    crates, problems = {}, []
    for spell in sorted(crate_spells, key=int):
        options = []
        for line in descriptions[spell].split("\n"):
            m = OPTION.match(line.strip())
            if not m:
                continue
            effect = effects[spell].get(int(m[1]) - 1)
            name = m[2]
            ids = by_name.get(name, [])
            item_id = AMBIGUOUS.get(name) if len(ids) > 1 else (ids[0] if ids else None)
            if not effect or not item_id:
                problems.append(f"spell {spell}: cannot resolve '{line.strip()}' (items {ids})")
                continue
            options.append((item_id, int(float(effect["EffectBasePointsF"])), name))
        for crate in crate_items.get(spell, []):
            crates[crate] = options

    lines = [
        "-- Waylaid Crates and the packages that fill them: { itemID, amount, English name }.",
        f"-- Generated by tools/update_data.py from build {build}: do not edit by hand.",
        "",
        "local _, ns = ...",
        "",
        "ns.crates = {",
    ]
    for crate in sorted(crates):
        lines.append(f"    [{crate}] = {{ -- {names.get(crate, '?')}")
        for item_id, amount, name in crates[crate]:
            lines.append(f"        {{ {item_id}, {amount}, {lua_string(name)} }},")
        lines.append("    },")
    lines += ["}", ""]
    out = ROOT / "Data" / "Crates.lua"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"{out.relative_to(ROOT)}: {len(crates)} crates")
    for p in problems:
        print("WARNING " + p)
    if problems:
        sys.exit(1)


if __name__ == "__main__":
    main()
